import express from 'express';
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const WEB = path.join(ROOT, 'web');
const DATA = path.join(ROOT, 'data');

const app = express();
const PORT = process.env.PORT || 3000;

app.disable('x-powered-by');
app.use(express.json({ limit: '200kb' }));

// Static front-end + data
app.use('/data', express.static(DATA, { maxAge: '1h' }));
app.use(express.static(WEB, { maxAge: '1h', extensions: ['html'] }));

// API: catalog (generated by tools/build-catalog.js, with fallback to curriculum only)
app.get('/api/catalog', (_req, res) => {
  const file = path.join(DATA, 'catalog.json');
  if (fs.existsSync(file)) return res.sendFile(file);
  res.status(404).json({ error: 'catalog.json chưa được tạo. Chạy: npm run catalog' });
});

app.get('/api/health', (_req, res) => {
  res.json({ ok: true, uptime: process.uptime(), ts: Date.now() });
});

// Feedback: append to var/feedback.jsonl (ignored by git)
app.post('/api/feedback', (req, res) => {
  const { sim, rating, message } = req.body || {};
  if (!sim || typeof message !== 'string' || message.length > 2000) {
    return res.status(400).json({ error: 'Thiếu dữ liệu hoặc nội dung quá dài' });
  }
  const dir = path.join(ROOT, 'var');
  fs.mkdirSync(dir, { recursive: true });
  const line = JSON.stringify({ ts: new Date().toISOString(), sim, rating, message }) + '\n';
  fs.appendFile(path.join(dir, 'feedback.jsonl'), line, (err) => {
    if (err) return res.status(500).json({ error: 'Không ghi được phản hồi' });
    res.json({ ok: true });
  });
});

// SPA fallback (hash router, but keep deep links safe)
app.get('*', (_req, res) => res.sendFile(path.join(WEB, 'index.html')));

app.listen(PORT, () => {
  console.log(`Science Phenomenons 12 đang chạy tại http://localhost:${PORT}`);
});
